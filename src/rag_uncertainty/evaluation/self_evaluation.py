"""Self-evaluation P(True) for RAG, adapted from Kadavath et al. (2022)"""

import torch
import json
import re
from pathlib import Path
from src.rag_uncertainty.config import SELF_EVAL_FEWSHOT_PATH

ANSWER_PREFIX = "La respuesta propuesta es: ("

_INSTRUCTION = (
    "Eres un verificador estricto. Se te da un CONTEXTO, una PREGUNTA y una RESPUESTA PROPUESTA. "
    "Debes decidir si la respuesta propuesta esta completamente respaldada por el contexto y responde a la pregunta. "
    "No uses tu propio conocimiento: aunque la respuesta sea medicamente correcta, es falsa si el contexto no contiene "
    "la información que afirma o si altera alguno de sus datos."
)

_QUESTION_BLOCK = (
    "¿Esta la respuesta propuesta completamente respaldada por el contexto?\n"
    "(A) Si\n"
    "(B) No\n"
)

_fewshot_cache: list | None = None
_option_ids_cache: dict = {}

def load_fewshot(path: Path = SELF_EVAL_FEWSHOT_PATH) -> list[dict]:
    """Loads fewshot examples

    Args:
        path (Path, optional): Path to the fewshot file. Defaults to SELF_EVAL_FEWSHOT_PATH.

    Raises:
        FileNotFoundError: If the fewshot file does not exist.

    Returns:
        list[dict]: A list of fewshot examples.
    """
    global _fewshot_cache
    if _fewshot_cache is None:
        if not Path(path).exists():
            raise FileNotFoundError(
                f"{path} doesn't exist."
            )
        with open(path, "r", encoding="utf-8") as f:
            _fewshot_cache = json.load(f)["examples"]
    return _fewshot_cache

def fewshot_origin_ids() -> list[str]:
    """Returns the origin_ids of the fewshot examples
    """
    return [e["origin_id"] for e in load_fewshot()]

def _format_item(context: str, query:str, answer: str) -> str:
    """Formats a single fewshot example or the final item for the self-evaluation prompt

    Args:
        context (str): The retrieved text context
        query (str): The input user query
        answer (str): The generated answer

    Returns:
        str: The formatted item for the self-evaluation prompt
    """
    return (
        f"CONTEXTO:\n{context}\n\n"
        f"PREGUNTA:\n{query}\n\n"
        f"RESPUESTA PROPUESTA:\n{answer}\n\n"
        f"{_QUESTION_BLOCK}"
    )
    
def strip_references(answer:str) -> str:
    """Deletes section 'Referencias' from final answer

    Args:
        answer (str): generated answer

    Returns:
        str: generated answer without 'Referencias' section
    """
    return re.split(r"\n\s*\**Referencias\**\s*:", answer, maxsplit=1, flags=re.IGNORECASE)[0].strip()

def build_self_eval_prompt(query: str, context:str, answer:str, render_context) -> str:
    """Builds the self evaluation prompt

    Args:
        query (str): The input user query
        context (str): The retrieved text context
        answer (str): The generated answer
        render_context (_type_): Function to render the context

    Returns:
        str: The self-evaluation prompt
    """
    shots = []
    for ex in load_fewshot():
        item = _format_item(render_context(ex["chunks"]), ex["question"], ex["answer"])
        shots.append(f"{item}{ANSWER_PREFIX}{ex["label"]})")
    final_item = _format_item(context, query, answer)
    sep = "\n\n---\n\n"
    return _INSTRUCTION + sep + sep.join(shots) + sep + final_item

def _get_option_ids(tokenizer) -> tuple[int, int]:
    """Returns the token ids for options A and B
    
    Args:
        tokenizer: The tokenizer used for the model
    
    Returns:
        tuple[int, int]: The token ids for options A and B
    """
    key = id(tokenizer)
    if key in _option_ids_cache:
        return _option_ids_cache[key]
    
    base = tokenizer.encode("(", add_special_tokens = False)
    ids = []
    for letter in ("A", "B"):
        full = tokenizer.encode(f"({letter}", add_special_tokens= False)
        if len(full) > len(base) and full[: len(base)] == base:
            ids.append(full[len(base)])
        else:
            ids.append(tokenizer.encode(letter, add_special_tokens=False)[0])
    if ids[0] == ids[1]:
        raise RuntimeError("Tokens A and B coincide. Revise tokenization.")
    _option_ids_cache[key] = (ids[0], ids[1])
    return _option_ids_cache[key]

def compute_p_true(query: str, context: str, answer: str, model, processor, render_context) -> dict:
    """Calculate P(True) for a generated answer

    Args:
        query (str): the input user query being answered
        context (str): the retrieved text context used as the source of truth
        answer (str): the raw response text generated by the model
        model (_type_): the language model used for text generation
        processor (_type_): the model's processor
        render_context (_type_): the function to render the context

    Returns:
        dict: 
            p_true = p_A / (p_A + p_B)
            mass_ab: (p_A + p_B) (Should be 1)
    """
    tokenizer = getattr(processor, "tokenizer", processor)
    body = strip_references(answer)
    eval_prompt = build_self_eval_prompt(query, context, body, render_context)
    
    if hasattr(processor, "apply_chat_template"):
        messages = [{"role": "user", "content": eval_prompt}]
        prompt_text = processor.apply_chat_template(messages, tokenize = False, add_generation_prompt = True)
    else:
        prompt_text = eval_prompt + "\n\n"
    prompt_text += ANSWER_PREFIX
    
    inputs = processor(text=prompt_text, add_special_tokens = False, return_tensors="pt").to(model.device)
    
    with torch.no_grad():
        try:
            out = model(**inputs, logits_to_keep = 1)
        except TypeError:
            out = model(**inputs)
        logits = out.logits[0,-1].float()
    
    id_a, id_b = _get_option_ids(tokenizer)
    log_probs = torch.log_softmax(logits, dim = -1)
    lp_a, lp_b = log_probs[id_a], log_probs[id_b]
    
    p_true = torch.sigmoid(lp_a-lp_b).item()
    mass_ab = (lp_a.exp() + lp_b.exp()).item()
    
    del out, logits, log_probs
    return {"p_true":p_true, "mass_ab":mass_ab}

