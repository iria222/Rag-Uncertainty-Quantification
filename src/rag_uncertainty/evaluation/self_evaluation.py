import torch

PROMPT_SELF_EVAL_TEMPLATE = """CONTEXTO:
{context}

PREGUNTA:
{query}

RESPUESTA PROPUESTA:
{answer}

Basándote exclusivamente en el contexto proporcionado, ¿es la respuesta propuesta verídica, correcta y responde adecuadamente a la pregunta?
(A) True
(B) False

La respuesta es:
"""

def evaluate_answer_by_prompt(query:str, context: str, raw_answer: str, model, processor) -> tuple[float, bool]:
    """Evaluate generated answer through autoevaluation prompting

    Args:
        query (str): the input user query being answer
        context (str): the retrieved text context used as the source of truth
        raw_answer (str): the raw response text generated by the model
        model (_type_): the language model used for text generation
        processor (_type_): the model's processor

    Returns:
        tuple[float, bool]: Probability assigned to option (A) True, boolean indicating if the model should abstain from answering.
    """
    
    if "[ABSTENCION]" in raw_answer:
        return 0.0, True
    
    eval_prompt = PROMPT_SELF_EVAL_TEMPLATE.format(
        context = context,
        query = query,
        answer = raw_answer
    )
    
    messages = [
        {"role": "user", "content":eval_prompt}
    ]
    
    if hasattr(processor, "apply_chat_template"):
        prompt_text = processor.apply_chat_template(messages, tokenize = False, add_generation_prompt= True)
    else:
        prompt_text = eval_prompt
        
    inputs = processor(text=prompt_text, return_tensors="pt").to(model.device)
    
    with torch.no_grad():
        outputs = model.generate(
            **inputs,
            max_new_tokens = 5,
            do_sample = False, # to evaluate deterministic logits
            return_dict_in_generate = True,
            output_scores = True,
        )
        
    # Extract the probability of the first token generated corresponding to the option (A) or (B)
    transition_scores = model.compute_transition_scores(outputs.sequences, outputs.scores, normalize_logits = True)
    
    # Obtain logits of first output token
    generated_token_ids = outputs.sequences[0][inputs["input_ids"].shape[1]:]
    
    if len(generated_token_ids) == 0:
        return 0.5, False
    
    first_token_id = generated_token_ids[0]
    
    token_a_ids = processor.tokenizer.encode("(A)", add_special_tokens = False)
    if not token_a_ids:
        token_a_ids = processor.tokenizer.encode("A", add_special_tokens = False)
    
    target_id = token_a_ids[0] if token_a_ids else None
    
    if target_id is not None:
        # Softmax over logits of first token
        first_token_logits = outputs.scores[0][0]
        probs = torch.softmax(first_token_logits, dim = -1)
        prob_true = probs[target_id].item()
    else:
        prob_true = 0.5
        
    # Abstention threshold (in paper is 0.5)
    must_abstain = prob_true < 0.5
    
    return prob_true, must_abstain